def partial(step):
    """3번째 힌트: 엔진 결과의 일부만 보여 준다 (최종 답은 감춤)."""
    n, r = step['n'], step['result']
    w = step['work']
    if n == 1:
        return w[1] if len(w) > 1 else w[0]
    if n == 2:
        return w[0].split('→')[0] + '→ 인수분해한 각 괄호를 0으로 놓아 보세요.'
    if n == 3:
        return w[0]
    if n == 4:
        return w[0] + ' / ' + (w[1] if len(w) > 1 else '')
    if n == 5:
        return w[1] if len(w) > 1 else w[0]
    if n == 6:
        lines = [x for x in w if x.strip().startswith(('+', '−'))]
        return '각 벡터의 각: ' + ' '.join(x.strip() for x in lines[:3]) if lines else w[0]
    if n == 7:
        first = [x for x in w if x.startswith('첫 열')]
        return first[0] if first else w[0]
    if n == 8:
        return w[0]
    if n == 9:
        return w[1] if len(w) > 1 else w[0]
    return w[0]


def ladder(step):
    """단계 결과 하나 → 힌트 4개"""
    n = step['n']
    return [
        {'level': 1, 'kind': '개념 질문', 'text': CONCEPT[n]},
        {'level': 2, 'kind': '적용 공식', 'text': FORMULA[n]},
        {'level': 3, 'kind': '계산 일부', 'text': partial(step)},
        {'level': 4, 'kind': '전체 풀이', 'text': '\n'.join(step['work'])},
    ]
